// Token Radar, model radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks only genuine pre-token protocols. A protocol is rankable when
// the snapshot records no token for it at all (no market cap, no CoinGecko id, no
// symbol) and it is not a wrapped, staked or bridged product of a token that
// already trades: its category is not CEX, Bridge, Canonical Bridge, Liquid
// Staking, Liquid Restaking or Restaked BTC, its name carries no whole word
// wrapped, staked or staking, does not begin with an exchange's name, and does
// not end in a version marker. That is the watchlist's own rule, applied to the
// whole snapshot, so the early rows below the floor are held to the same bar as
// the watchlist. The watchlist is the floor: all 40 of its slugs are covered,
// and 158 rankable protocols below the $50M floor join them, for 198 rows.
//
// Implied value follows only from the snapshot's own figures, through one
// function that scores every protocol the same way:
//
//   category multiple  a FDV/TVL multiple by category, from the category
//                       string alone (Dexs trade dearer per TVL dollar than
//                       a generic app, a yield farm cheaper); never a name.
//   base               = tvl_usd x category_multiple
//   growth             = clamp(change_7d, -60, 120) per cent
//   growth multiplier  = 1 + (growth / 100) x 0.6
//   maturity           = 0.55 + min(age_days, 1095) / 1095 x 0.45
//                       (age is days since first listed; unknown age uses 365)
//   chain multiplier   = 1 + min(chains - 1, 4) x 0.03
//                       (a protocol live on more chains reaches more farmers)
//   implied            = round(base x growth x maturity x chain), at least $1
//
// Live-token protocols are kept apart: the board never ranks a protocol whose
// token already trades, and the dashboard shows the top 48 of them by market
// cap with the market's own value, never a model's.

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  chain_step: number;
  chain_max_steps: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.6,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.55,
  maturity_range: 0.45,
  maturity_days: 1095,
  unknown_age_days: 365,
  chain_step: 0.03,
  chain_max_steps: 4,
};

export const MODEL_VERSION = 'radar-2';

